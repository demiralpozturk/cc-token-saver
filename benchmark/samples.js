/**
 * Deterministic, synthetic sample files and command outputs for the benchmark.
 * They imitate the structure of real files/outputs (npm lockfile v3, npm install,
 * pytest -v, jest, next build) but are generated, so the benchmark is reproducible
 * and contains no third-party content.
 */

function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const SYL = ['re', 'act', 'lo', 'dash', 'ex', 'press', 'ba', 'bel', 'core', 'js', 'type', 'script', 'web', 'pack', 'es', 'lint', 'jest', 'vi', 'te', 'post', 'css', 'tail', 'wind', 'node', 'fetch', 'ax', 'ios', 'chalk', 'debug', 'ms', 'glob', 'semver', 'yargs', 'commander', 'ansi', 'styles', 'color', 'convert', 'string', 'width', 'strip', 'regex', 'is', 'fullwidth', 'emoji', 'source', 'map', 'support', 'buffer', 'from'];

function names(count, seed) {
  const r = rng(seed);
  const out = new Set();
  while (out.size < count) {
    const parts = 1 + Math.floor(r() * 3);
    let n = '';
    for (let i = 0; i < parts; i++) n += (i ? '-' : '') + SYL[Math.floor(r() * SYL.length)] + SYL[Math.floor(r() * SYL.length)];
    if (r() < 0.15) n = '@' + SYL[Math.floor(r() * SYL.length)] + '/' + n;
    out.add(n);
  }
  return [...out];
}

function b64(r, len) {
  const abc = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
  let s = '';
  for (let i = 0; i < len; i++) s += abc[Math.floor(r() * 64)];
  return s;
}

function version(r) {
  return `${Math.floor(r() * 12)}.${Math.floor(r() * 30)}.${Math.floor(r() * 20)}`;
}

/** package-lock.json (lockfileVersion 3) with `count` packages. */
function packageLock(count, seed = 1) {
  const r = rng(seed);
  const list = names(count, seed + 7);
  const packages = { '': { name: 'demo-app', version: '1.0.0', dependencies: {}, devDependencies: {} } };
  for (const n of list.slice(0, 20)) packages[''].dependencies[n] = '^' + version(r);
  for (const n of list) {
    const v = version(r);
    const entry = {
      version: v,
      resolved: `https://registry.npmjs.org/${n}/-/${n.split('/').pop()}-${v}.tgz`,
      integrity: 'sha512-' + b64(r, 86) + '==',
    };
    if (r() < 0.4) entry.dev = true;
    if (r() < 0.5) {
      entry.dependencies = {};
      const k = 1 + Math.floor(r() * 4);
      for (let i = 0; i < k; i++) entry.dependencies[list[Math.floor(r() * list.length)]] = '^' + version(r);
    }
    if (r() < 0.2) entry.engines = { node: '>=' + (12 + Math.floor(r() * 8)) };
    if (r() < 0.1) entry.license = 'MIT';
    packages['node_modules/' + n] = entry;
  }
  return JSON.stringify({ name: 'demo-app', version: '1.0.0', lockfileVersion: 3, requires: true, packages }, null, 2) + '\n';
}

/** yarn.lock (v1 format). */
function yarnLock(count, seed = 2) {
  const r = rng(seed);
  const out = ['# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.', '# yarn lockfile v1', ''];
  for (const n of names(count, seed + 3)) {
    const v = version(r);
    out.push(`"${n}@^${v}":`, `  version "${v}"`, `  resolved "https://registry.yarnpkg.com/${n}/-/${n.split('/').pop()}-${v}.tgz#${b64(r, 40).replace(/[+/]/g, 'a')}"`, `  integrity sha512-${b64(r, 86)}==`);
    if (r() < 0.5) {
      out.push('  dependencies:');
      for (let i = 0; i < 1 + Math.floor(r() * 3); i++) out.push(`    ${SYL[Math.floor(r() * SYL.length)]}-${SYL[Math.floor(r() * SYL.length)]} "^${version(r)}"`);
    }
    out.push('');
  }
  return out.join('\n');
}

/** A minified bundle: one very long line. */
function minifiedBundle(bytes, seed = 3) {
  const r = rng(seed);
  let s = '/*! demo vendor bundle */!function(){"use strict";var e={};';
  let i = 0;
  while (s.length < bytes) {
    const id = Math.floor(r() * 1e6).toString(36);
    s += `function ${id}${i}(t,n,o){return void 0===n?t.${id}:t.${id}=n||o,e[${i}]=t}var ${id}_${i}=[${Math.floor(r() * 99)},"${id}"];`;
    i++;
  }
  return s + '}();\n';
}

function sourceMap(bytes, seed = 4) {
  const r = rng(seed);
  const segs = [];
  let len = 0;
  while (len < bytes - 200) {
    const s = b64(r, 4 + Math.floor(r() * 4)).replace(/[+/]/g, 'A');
    segs.push(s);
    len += s.length + 1;
  }
  return JSON.stringify({ version: 3, file: 'app.js', sources: ['../src/app.ts'], names: [], mappings: segs.join(',') }) + '\n';
}

